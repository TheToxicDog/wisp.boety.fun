#!/usr/bin/env bash
# Syncs Cloudflare's published IP ranges into:
#   1. Nginx real-IP config (so logs and the Wisp relay see the true client IP)
#   2. UFW rules allowing 80/443 only from Cloudflare (hides/shields the origin)
# Run as root. Safe to re-run; schedule weekly:
#   echo '17 4 * * 1 root /opt/wisp.boety.fun/scripts/cloudflare-sync.sh' > /etc/cron.d/cloudflare-sync
set -euo pipefail

CONF=/etc/nginx/conf.d/cloudflare-realip.conf
V4=$(curl -fsS https://www.cloudflare.com/ips-v4)
V6=$(curl -fsS https://www.cloudflare.com/ips-v6)
[ -n "$V4" ] && [ -n "$V6" ] || { echo "empty IP list from Cloudflare" >&2; exit 1; }

{
  echo "# Generated by cloudflare-sync.sh on $(date -u +%FT%TZ)"
  for ip in $V4 $V6; do echo "set_real_ip_from $ip;"; done
  echo "real_ip_header CF-Connecting-IP;"
} > "$CONF.tmp"
mv "$CONF.tmp" "$CONF"
nginx -t && systemctl reload nginx

if command -v ufw >/dev/null && [ "${SKIP_UFW:-0}" != 1 ]; then
  # Remove previous Cloudflare rules, then re-add the current ranges.
  while ufw status numbered | grep -q 'cloudflare'; do
    n=$(ufw status numbered | grep 'cloudflare' | head -1 | sed -E 's/^\[ *([0-9]+)\].*/\1/')
    yes | ufw delete "$n" >/dev/null
  done
  for ip in $V4 $V6; do
    ufw allow proto tcp from "$ip" to any port 80,443 comment cloudflare >/dev/null
  done
  ufw delete allow 80/tcp >/dev/null 2>&1 || true
  ufw delete allow 443/tcp >/dev/null 2>&1 || true
  ufw delete allow 'Nginx Full' >/dev/null 2>&1 || true
  echo "UFW: 80/443 restricted to $(echo $V4 $V6 | wc -w) Cloudflare ranges"
fi
echo "Wrote $CONF"
